</p>
<p>
  <strong>Участие в звонках.</strong> В звонок какой комнаты и когда вы вошли и когда вышли; с какого клиента (приложение,
  браузер или телефон), операционная система и браузер; как шла связь по оценке вашего приложения (хорошо, нестабильно или
