<p><strong>Push-уведомления</strong>, если вы их включили: адрес подписки и ключи шифрования, которые выдал браузер.</p>
<p><strong>Жалобы.</strong> Кто пожаловался, на какое сообщение, причина и комментарий.</p>
<p>
