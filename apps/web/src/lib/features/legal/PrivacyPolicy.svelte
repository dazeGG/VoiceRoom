</p>
<p>
  <strong>Сеансы и вход.</strong> Сессионный cookie, название браузера и операционной системы, а также город и страна, которые
  определяются по IP-адресу при входе с помощью локальной базы геоданных на нашем сервере. Сам IP-адрес в базе данных аккаунта
  не сохраняется. История входов используется, чтобы предупреждать вас о входе с незнакомого устройства.
</p>
<p>
  <strong>Общение.</strong> Сообщения в комнатах и личные сообщения, изображения во вложениях, реакции, закреплённые сообщения,
  упоминания, отметки о прочтении, список друзей и заявок, блокировки пользователей, комнаты, которые вы создали или в которых
  состоите.
</p>
<p>
  <strong>Голос, видео и демонстрация экрана</strong> передаются участникам комнаты в реальном времени через медиасервер
  на нашем сервере. Мы <strong>не записываем и не храним</strong> звонки.
</p>
<p>
  <strong>Гости без аккаунта.</strong> Имя, которое гость указал для комнаты, и его сообщения в комнате. IP-адрес создателя
  временной комнаты и IP-адрес гостя, заблокированного в комнате, хранятся, чтобы ограничивать злоупотребления.
</p>
<p><strong>Push-уведомления</strong>, если вы их включили: адрес подписки и ключи шифрования, которые выдал браузер.</p>
<p><strong>Жалобы.</strong> Кто пожаловался, на какое сообщение, причина и комментарий.</p>
<p>
